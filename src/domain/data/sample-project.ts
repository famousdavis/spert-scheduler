/** Add calendar days to an ISO date, returning ISO. */
function addCalendarDays(startISO: string, days: number): string {
  const d = new Date(`${startISO}T00:00:00`);
  d.setDate(d.getDate() + days);
  return d.toISOString().slice(0, 10);
}

/**
 * Build the canonical sample project.
 *
 * The returned Project carries placeholder `id`/`createdAt` and a null `owner`:
 * callers are expected to pass it through cloneProject(), which mints a fresh
 * project id, re-mints every entity id, remaps all cross-references, and stamps
 * the current SCHEMA_VERSION. The store action then sets `owner` per storage mode.
 *
 * @param startDate - Scenario start, ISO `YYYY-MM-DD`. Milestone targets are
 *   derived from it, so the sample reads as current whenever it is loaded.
 * @param holidays - Optional project-level holidays. Passed in rather than
 *   computed here because the US federal holiday calculator lives in `/core`
 *   and `/domain` must never import upward. Callers in the app/UI layer are
 *   expected to build this from `getUSHolidays()` for the years the sample
 *   spans, so the calendar tracks the load date instead of ageing.
 */
export function createSampleProject(
  startDate: string,
  holidays?: readonly Holiday[],
): Project {
  const milestones: Milestone[] = MILESTONE_OFFSETS.map((m) => ({
    id: m.id,
    name: m.name,
    targetDate: addCalendarDays(startDate, m.offsetDays),
  }));

  const scenario: Scenario = {
    id: "sample-baseline",
    name: "Baseline",
    startDate,
    activities: ACTIVITIES.map((a) => ({
      ...a,
      checklist: a.checklist?.map((c) => ({ ...c })),
      deliverables: a.deliverables?.map((d) => ({ ...d })),
    })),
    dependencies: DEPENDENCIES.map((d) => ({ ...d })),
    milestones,
    bands: BANDS.map((b) => ({ ...b })),
    settings: {
      ...DEFAULT_SCENARIO_SETTINGS,
      rngSeed: "sample-cloud-erp",
      dependencyMode: true,
      // Lower than the 50k default: a new user's first run should feel instant.
      // Still ample for a stable P95 on a 40-activity network.
      trialCount: 10_000,
    },
  };

  return {
    id: "sample-cloud-erp",
    name: SAMPLE_PROJECT_NAME,
    createdAt: new Date().toISOString(),
    schemaVersion: SCHEMA_VERSION,
    owner: null,
    // Numbers the grid rows 1-40 so the sample's activities are easy to cite.
    showActivityIds: true,
    ...(holidays && holidays.length > 0
      ? { globalCalendarOverride: { holidays: holidays.map((h) => ({ ...h })) } }
      : {}),
    scenarios: [scenario],
  };
}
